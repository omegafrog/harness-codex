@dataclass(frozen=True)
class HarvestUiResult:
    initial_prompt: str
    status: str
    active_stage: str
    requirements_markdown: str
    use_cases_markdown: str
    clarifications: tuple[dict[str, Any], ...]
    current_question: dict[str, Any] | None
