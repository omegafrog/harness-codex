def _question_key(text: str) -> str:
    normalized = re.sub(r"[^0-9a-zA-Z가-힣]+", "", text).lower()
    stop_words = (
        "무엇인가요",
        "무엇입니까",
        "무엇인지",
        "어떤",
        "알려주세요",
        "확인해주세요",
        "해주세요",
        "인가요",
        "입니까",
        "please",
        "what",
        "which",
        "tell",
        "about",
        "the",
        "a",
        "an",
    )
    for word in stop_words:
        normalized = normalized.replace(word, "")
    return normalized[:120]


