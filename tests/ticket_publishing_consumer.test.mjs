import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { updateProject } from '../.harness/src/installer/update.mjs';
import { protectLocalInstallArtifacts } from '../.harness/src/installer/local-exclude.mjs';
import { runDoctor } from '../.harness/src/doctor/doctor.mjs';

test('installed and updated ticket guidance and renderer retain relations and verification', async () => {
  const sourceRoot = resolve('.');
  await mkdir('.io', { recursive: true });
  const root = await mkdtemp(resolve('.io/ticket-consumer-'));
  execFileSync('git', ['init', '-q', root]);
  await protectLocalInstallArtifacts(root, sourceRoot);
  await updateProject({ sourceRoot, targetRoot: root, initialize: true });
  const guidePath = join(root, '.codex/internal-skills/to-ticket/references/github-batch-publish.md');
  const publisherPath = join(root, '.codex/internal-skills/tracker-publish/GUIDE.md');
  const templatePath = join(root, '.codex/internal-skills/to-ticket/references/github-issue-template.md');
  const implementationPath = join(root, '.codex/internal-skills/implement-wrapper/references/tracker/github.md');
  const implementationSkillPath = join(root, '.codex/internal-skills/implement-wrapper/GUIDE.md');
  const productTemplatePath = join(root, '.codex/internal-skills/product-spec/references/template.md');
  const diagramGuidePath = join(root, '.codex/internal-skills/plantuml-diagrams/GUIDE.md');
  const architectureTemplatePath = join(root, '.codex/internal-skills/architecture-spec/references/template.md');
  const dddGuidePath = join(root, '.codex/internal-skills/ddd-design/GUIDE.md');
  const plannerProfiles = ['.codex/agents/to_ticket.toml', '.claude/agents/to_ticket.md'];
  const checkPlanningGuidance = async () => {
    for (const path of plannerProfiles) {
      const profile = await readFile(join(root, path), 'utf8');
      assert.match(profile, /internal-skills\/to-ticket\/GUIDE\.md/);
      assert.doesNotMatch(profile, /\.(?:codex|agents|claude)\/skills\/to-ticket\/SKILL\.md/);
    }
    const guide = await readFile(join(root, '.codex/internal-skills/to-ticket/GUIDE.md'), 'utf8');
    assert.match(guide, /their absence or empty content is not a plan-authoring prerequisite/);
    assert.match(guide, /Preserve the actual workspace identity, approved Spec\/review/);
  };
  const checkArchitectureGuidance = async () => {
    const template = await readFile(architectureTemplatePath, 'utf8');
    const headings = ['# 2. Domain', '# 3. Aggregate', '# 4. Application Service', '# 5. Bounded Context'];
    const positions = headings.map((heading) => template.indexOf(heading));
    assert.ok(positions.every((position, index) => position >= 0 && (!index || position > positions[index - 1])));
    assert.match(template, /설계 대상 도메인에 하나 이상의 Aggregate를 정의/);
    assert.match(template, /모든 Aggregate에는 Root Entity/);
    assert.doesNotMatch(template, /## 1\.2 Product Spec Mapping|## 2\.7 Hotspots|## 3\.7 Business Rule Ownership/);
    const guide = await readFile(dddGuidePath, 'utf8');
    assert.match(guide, /Each Aggregate has a root Entity/);
    assert.doesNotMatch(guide, /Treat creation of a new bounded context as a promotion decision/);
  };
  const freshGuide = await readFile(guidePath, 'utf8');
  assert.match(freshGuide, /필요한 비테스트 검증을 템플릿의 해당 위치에 옮겨 적는다/);
  assert.match(freshGuide, /GitHub Issue 본문 템플릿/);
  assert.match(await readFile(publisherPath, 'utf8'), /github-issue-template\.md/);
  assert.match(await readFile(publisherPath, 'utf8'), /Do not run a separate post-authoring body validation pass/);
  assert.match(await readFile(publisherPath, 'utf8'), /never create repository Issues in this stage/i);
  assert.match(await readFile(publisherPath, 'utf8'), /converted `Issue` is already published when its stable plan marker or exact approved body matches/);
  assert.match(await readFile(implementationPath, 'utf8'), /convertProjectV2DraftIssueItemToIssue/);
  assert.match(await readFile(implementationSkillPath, 'utf8'), /구현할 plan ID로 plan-set draft 활성화를 시작한다/);
  assert.match(await readFile(templatePath, 'utf8'), /## Parent Issue[\s\S]*## Child Issue/);
  assert.match(await readFile(templatePath, 'utf8'), /작성하면서 적용할 규칙/);
  assert.match(freshGuide, /완성된 본문을 다시 대조하는 단계를 두지 않는다/);
  assert.match(freshGuide, /Project draft item만 만든다/);
  assert.match(await readFile(productTemplatePath, 'utf8'), /`\.puml` 원본과 생성된 `\.svg`를 각각 상대 경로 Markdown 링크/);
  assert.match(await readFile(diagramGuidePath, 'utf8'), /Product Spec Markdown은 편집 가능한 `\.puml` 원본과 생성된 SVG를 각각 상대 경로 링크/);
  await checkArchitectureGuidance();
  await assert.rejects(readFile(join(root, 'AGENTS.md')), { code: 'ENOENT' });
  await checkPlanningGuidance();
  await mkdir(join(root, 'docs/agents'), { recursive: true });
  await writeFile(join(root, 'docs/agents/EXEC.md'), '');
  // A previous managed release must update both native profiles without force.
  const lockPath = join(root, '.codex/harness-lock.json');
  const lock = JSON.parse(await readFile(lockPath, 'utf8'));
  for (const path of plannerProfiles) {
    const native = path.startsWith('.claude/') ? '.claude' : '.agents';
    const old = (await readFile(join(root, path), 'utf8')).replaceAll('.codex/internal-skills/to-ticket/GUIDE.md', `${native}/skills/to-ticket/SKILL.md`);
    await writeFile(join(root, path), old);
    lock.files[path].installed_sha256 = createHash('sha256').update(old).digest('hex');
    lock.files[path].upstream_sha256 = lock.files[path].installed_sha256;
  }
  await writeFile(lockPath, JSON.stringify(lock));
  await writeFile(join(root, 'CONTEXT.md'), 'project-owned glossary');
  await updateProject({ sourceRoot, targetRoot: root });
  await checkPlanningGuidance();
  await assert.rejects(readFile(join(root, 'AGENTS.md')), { code: 'ENOENT' });
  assert.equal(await readFile(join(root, 'docs/agents/EXEC.md'), 'utf8'), '');
  const guide = await readFile(guidePath, 'utf8');
  assert.match(guide, /필요한 비테스트 검증을 템플릿의 해당 위치에 옮겨 적는다/);
  assert.match(guide, /GitHub Issue 본문 템플릿/);
  assert.match(await readFile(publisherPath, 'utf8'), /github-issue-template\.md/);
  assert.match(await readFile(publisherPath, 'utf8'), /Do not run a separate post-authoring body validation pass/);
  assert.match(await readFile(publisherPath, 'utf8'), /never create repository Issues in this stage/i);
  assert.match(await readFile(publisherPath, 'utf8'), /Do not reset an existing Issue to Planned/);
  assert.match(await readFile(implementationPath, 'utf8'), /convertProjectV2DraftIssueItemToIssue/);
  assert.match(await readFile(implementationSkillPath, 'utf8'), /구현할 plan ID로 plan-set draft 활성화를 시작한다/);
  assert.match(await readFile(guidePath, 'utf8'), /완성된 본문을 다시 대조하는 단계를 두지 않는다/);
  assert.match(await readFile(guidePath, 'utf8'), /Project draft item만 만든다/);
  assert.match(await readFile(productTemplatePath, 'utf8'), /`\.puml` 원본과 생성된 `\.svg`를 각각 상대 경로 Markdown 링크/);
  assert.match(await readFile(diagramGuidePath, 'utf8'), /Product Spec Markdown은 편집 가능한 `\.puml` 원본과 생성된 SVG를 각각 상대 경로 링크/);
  await checkArchitectureGuidance();
  assert.equal(await readFile(join(root, 'CONTEXT.md'), 'utf8'), 'project-owned glossary');
  const { renderSplitPlanIssue } = await import(pathToFileURL(join(root, '.harness/src/tracker/render.mjs')));
  const plan = { schema_version: 1, kind: 'split-plan', plan_id: 'ui', issue: 11, parent_issue: 9, status: 'Planned', purpose: '계산 결과를 표시한다.', scope: ['workspace_root: /workspace', 'workspace_branch: feature', '화면을 구현한다.'], acceptance_criteria: ['결과 14가 표시된다.'], test_contract: { unit_policy: '없음', ui_entity_e2e: '상위 이슈' }, verification: ['키보드와 오류 보존을 확인한다.'], dependencies: [10], specs: { product_spec: 'product.md', architecture_spec: 'architecture.md' } };
  const body = renderSplitPlanIssue(plan);
  assert.match(body, /상위 이슈: #9\n\n## 상태/);
  assert.match(body, /## 의존성\n\n#10/);
  assert.match(body, /키보드와 오류 보존을 확인한다/);
  assert.match(body, /<details><summary>실행 정보<\/summary>[\s\S]*workspace_root: \/workspace/);
  const { verification, ...legacyPlan } = plan;
  assert.doesNotMatch(renderSplitPlanIssue(legacyPlan), /필요한 비테스트 검증/);
  await mkdir(join(root, 'docs/agents'), { recursive: true });
  await writeFile(join(root, 'docs/agents/EXEC.md'), 'project-owned');
  await writeFile(join(root, 'app.js'), 'application change');
  await writeFile(join(root, 'AGENTS.md'), 'project-owned instructions');
  const status = execFileSync('git', ['status', '--short', '--untracked-files=all'], { cwd: root, encoding: 'utf8' });
  assert.match(status, /docs\/agents\/EXEC\.md/);
  assert.match(status, /CONTEXT\.md/);
  assert.match(status, /app\.js/);
  assert.match(status, /AGENTS\.md/);
  assert.equal(await readFile(join(root, 'AGENTS.md'), 'utf8'), 'project-owned instructions');
  assert.equal(await readFile(join(root, 'app.js'), 'utf8'), 'application change');
  assert.doesNotMatch(status, /\.harness\/src\/|\.agents\/skills\//);
  execFileSync('git', ['check-ignore', '-v', '.harness/src/tracker/render.mjs', '.codex/internal-skills/to-ticket/references/github-batch-publish.md', ...plannerProfiles], { cwd: root });
  const doctor = await runDoctor({ root, sourceRoot });
  assert.equal(doctor.diagnostics.some((item) => item.code === 'execution_asset_missing'), false);
});
