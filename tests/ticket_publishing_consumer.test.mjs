import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { updateProject } from '../.harness/src/installer/update.mjs';
import { protectLocalInstallArtifacts } from '../.harness/src/installer/local-exclude.mjs';
import { runDoctor } from '../.harness/src/doctor/doctor.mjs';

test('installed and updated ticket guidance and renderer retain relations and verification', async () => {
  const sourceRoot = resolve('.');
  await mkdir('.io', { recursive: true });
  const root = await mkdtemp(resolve('.io/ticket-consumer-'));
  execFileSync('git', ['init', '-q', root]);
  await protectLocalInstallArtifacts(root, sourceRoot);
  await updateProject({ sourceRoot, targetRoot: root, initialize: true });
  const guidePath = join(root, '.harness/skills/planning/to-ticket/references/github-batch-publish.md');
  const publisherPath = join(root, '.harness/skills/planning/tracker-publish/GUIDE.md');
  const templatePath = join(root, '.harness/skills/planning/to-ticket/references/github-issue-template.md');
  const implementationPath = join(root, '.harness/skills/delivery/tactical-code/references/tracker/github.md');
  const implementationSkillPath = join(root, '.harness/skills/delivery/tactical-code/GUIDE.md');
  const diagramGuidePath = join(root, '.harness/skills/quality/plantuml-diagrams/GUIDE.md');
  const modelContinuityPath = join(root, '.harness/skills/requirements/bounded-context/references/model-continuity.md');
  const plannerProfiles = ['.codex/agents/to_ticket.toml', '.claude/agents/to_ticket.md'];
  const checkPlanningGuidance = async () => {
    for (const path of plannerProfiles) {
      const profile = await readFile(join(root, path), 'utf8');
      assert.match(profile, /\.harness\/skills\/planning\/to-ticket\/GUIDE\.md/);
      assert.doesNotMatch(profile, /\.(?:codex|agents|claude)\/skills\/to-ticket\/SKILL\.md/);
    }
    const guide = await readFile(join(root, '.harness/skills/planning/to-ticket/GUIDE.md'), 'utf8');
    assert.match(guide, /their absence or empty content is not a plan-authoring prerequisite/);
    assert.match(guide, /Preserve the actual workspace identity, the settled tactical design and decision documents/);
    assert.doesNotMatch(guide, /Product and Architecture Specs|approved Specs/);
  };
  const checkArchitectureGuidance = async () => {
    const contract = await readFile(modelContinuityPath, 'utf8');
    assert.match(contract, /기존 소유 모델을 확장/);
    assert.match(contract, /Aggregate/);
  };
  const checkPublishingGuidance = async () => {
    const guide = await readFile(guidePath, 'utf8');
    const publisher = await readFile(publisherPath, 'utf8');
    const template = await readFile(templatePath, 'utf8');
    assert.match(guide, /전체 계획이 독립 리뷰를 통과하고 사용자가 발행을 승인한 뒤/);
    assert.match(guide, /harness-publication\.mjs publish.*parent·child Issue를 직접 만든다/);
    assert.match(guide, /발행 후에도 canonical 계획 snapshot을 보존한다/);
    assert.match(publisher, /github-issue-template\.md/);
    assert.match(publisher, /harness-publication\.mjs activate --root <workspace_root> --plan-set <plan_set_id>/);
    assert.match(publisher, /approved plan bodies and stable plan markers identify repository Issues/);
    assert.match(publisher, /Project registration is optional/);
    assert.match(await readFile(implementationPath, 'utf8'), /미변환 draft를 구현 차단 사유로 반환하지 않는다/);
    assert.match(await readFile(implementationSkillPath, 'utf8'), /모든 tracker mode에서 정본은/);
    assert.match(template, /## Parent Issue[\s\S]*## Child Issue/);
    assert.match(template, /작성하면서 적용할 규칙/);
    assert.match(template, /원본 ticket의 모든 필수 테스트와 비테스트 검증을 보존한다/);
    assert.match(template, /publisher는 정적 준비기의 `publication_drafts` 본문 파일을 그대로 사용한다/);
    assert.match(await readFile(diagramGuidePath, 'utf8'), /`requirements\.md`은 편집 가능한 `\.puml` 원본과 생성된 SVG를 각각 상대 경로 링크/);
  };
  await checkPublishingGuidance();
  await checkArchitectureGuidance();
  await assert.rejects(readFile(join(root, 'AGENTS.md')), { code: 'ENOENT' });
  await checkPlanningGuidance();
  await mkdir(join(root, '.harness/agents'), { recursive: true });
  await writeFile(join(root, '.harness/agents/EXEC.md'), '');
  // A previous managed release must update both native profiles without force.
  const lockPath = join(root, '.codex/harness-lock.json');
  const lock = JSON.parse(await readFile(lockPath, 'utf8'));
  for (const path of plannerProfiles) {
    const native = path.startsWith('.claude/') ? '.claude' : '.agents';
    const old = (await readFile(join(root, path), 'utf8')).replaceAll('.harness/skills/planning/to-ticket/GUIDE.md', `${native}/skills/to-ticket/SKILL.md`);
    await writeFile(join(root, path), old);
    lock.files[path].installed_sha256 = createHash('sha256').update(old).digest('hex');
    lock.files[path].upstream_sha256 = lock.files[path].installed_sha256;
  }
  await writeFile(lockPath, JSON.stringify(lock));
  await writeFile(join(root, 'CONTEXT.md'), 'project-owned glossary');
  await updateProject({ sourceRoot, targetRoot: root });
  await checkPlanningGuidance();
  await assert.rejects(readFile(join(root, 'AGENTS.md')), { code: 'ENOENT' });
  assert.equal(await readFile(join(root, '.harness/agents/EXEC.md'), 'utf8'), '');
  await checkPublishingGuidance();
  await checkArchitectureGuidance();
  assert.equal(await readFile(join(root, 'CONTEXT.md'), 'utf8'), 'project-owned glossary');
  const { renderSplitPlanIssue } = await import(pathToFileURL(join(root, '.harness/src/tracker/render.mjs')));
  const plan = { schema_version: 1, kind: 'split-plan', plan_id: 'ui', issue: 11, parent_issue: 9, status: 'Planned', purpose: '계산 결과를 표시한다.', scope: ['workspace_root: /workspace', 'workspace_branch: feature', '화면을 구현한다.'], acceptance_criteria: ['결과 14가 표시된다.'], test_contract: { unit_policy: '없음', ui_entity_e2e: '상위 이슈' }, verification: ['키보드와 오류 보존을 확인한다.'], dependencies: [10], design: ['docs/specs/demo/tactical-design.md', 'docs/implementation/demo/api.md'] };
  const body = renderSplitPlanIssue(plan);
  assert.match(body, /상위 이슈: #9\n\n## 상태/);
  assert.match(body, /## 의존성\n\n#10/);
  assert.match(body, /키보드와 오류 보존을 확인한다/);
  assert.match(body, /<details><summary>실행 정보<\/summary>[\s\S]*workspace_root: \/workspace/);
  assert.match(body, /## 관련 설계\n\n- docs\/specs\/demo\/tactical-design\.md\n- docs\/implementation\/demo\/api\.md/);
  assert.doesNotMatch(body, /Product Spec|Architecture Spec/);
  assert.doesNotMatch(renderSplitPlanIssue({ ...plan, test_contract: { unit_policy: '없음' } }), /ui ~ entity/, 'a ticket without an E2E carries none');
  assert.throws(() => renderSplitPlanIssue({ ...plan, design: [] }), /plan.design|design must be a non-empty list/);
  const { verification, ...legacyPlan } = plan;
  assert.doesNotMatch(renderSplitPlanIssue(legacyPlan), /필요한 비테스트 검증/);
  await mkdir(join(root, '.harness/agents'), { recursive: true });
  await writeFile(join(root, '.harness/agents/EXEC.md'), 'project-owned');
  await writeFile(join(root, 'app.js'), 'application change');
  await writeFile(join(root, 'AGENTS.md'), 'project-owned instructions');
  const status = execFileSync('git', ['status', '--short', '--untracked-files=all'], { cwd: root, encoding: 'utf8' });
  assert.match(status, /\.harness\/agents\/EXEC\.md/);
  assert.match(status, /CONTEXT\.md/);
  assert.match(status, /app\.js/);
  assert.match(status, /AGENTS\.md/);
  assert.equal(await readFile(join(root, 'AGENTS.md'), 'utf8'), 'project-owned instructions');
  assert.equal(await readFile(join(root, 'app.js'), 'utf8'), 'application change');
  assert.doesNotMatch(status, /\.harness\/src\/|\.agents\/skills\//);
  execFileSync('git', ['check-ignore', '-v', '.harness/src/tracker/render.mjs', '.harness/skills/planning/to-ticket/references/github-batch-publish.md', ...plannerProfiles], { cwd: root });
  const doctor = await runDoctor({ root, sourceRoot });
  assert.equal(doctor.diagnostics.some((item) => item.code === 'execution_asset_missing'), false);
});
